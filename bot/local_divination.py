def _deck():
    cards = [(n, u, r) for (n, u, r) in MAJOR]
    for suit, elem, theme, prog in SUITS:
        for i, kw in enumerate(prog, 1):
            cards.append(("%s%d" % (suit, i), "%s·%s" % (theme, kw), "%s受阻·%s过度" % (theme, kw)))
        for cn, ck in COURT:
            cards.append(("%s%s" % (suit, cn), "%s·%s" % (theme, ck), "%s失衡·%s" % (theme, ck)))
    return cards  # 22 + 4*14 = 78


def _draw(n):
    deck = _deck()
    idx = _R.sample(range(len(deck)), n)
    out = []
    for i in idx:
        name, up, rev = deck[i]
        upright = _R.randrange(2) == 0
        out.append({"name": name, "upright": upright,
                    "meaning": up if upright else rev})
    return out


def tarot(question=""):
    q = str(question or "")
    if any(k in q for k in ("二选一", "选择", "两个", "选哪")):
        positions = ["选项A", "选项B", "建议"]
    elif any(k in q for k in ("单张", "一张", "建议")):
        positions = ["当前建议"]
    else:
        positions = ["过去", "现在", "未来"]
    cards = _draw(len(positions))
    lines = ["这次是我自己用加密随机源摇的牌（78 张全牌堆，正逆位同随机）。"]
    for pos, c in zip(positions, cards):
        lines.append("【%s】%s · %s：%s" % (
            pos, c["name"], "正位" if c["upright"] else "逆位", c["meaning"]))
    lines.append("综合：%s。牌面是参考，路还是你自己走。" % _synth(cards))
    return {"ok": True, "text": "\n".join(lines)}


def _synth(cards):
    ups = sum(1 for c in cards if c["upright"])
    if ups == len(cards):
        return "整体顺，宜推进"
    if ups == 0:
        return "整体宜缓，先理顺再动"
    return "顺阻并存，抓正位的方向、补逆位的短板"


